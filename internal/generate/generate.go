// Package generate renders Kubernetes manifests from a validated topology:
// a Namespace, one ConfigMap+Deployment+Service per zealot service (the
// ConfigMap carries the rendered node config), a Deployment+Service per
// datastore (Postgres gets a PVC and an initdb ConfigMap for seedSQL), and
// optional ServiceMonitors for the Prometheus Operator.
//
// The input contract is a *validated* topology.Topology: defaults
// (namespace, replicas, datastore type/image/database) are applied by
// topology.Validate, which `zealot generate` runs before rendering.
package generate

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/chriswood123/zealot/internal/config"
	"github.com/chriswood123/zealot/internal/topology"
)

const (
	// zealotPort is the container port every generated node listens on;
	// Services map port 80 to it so bare `call` targets (http://<name>)
	// resolve via cluster DNS.
	zealotPort = 8080

	// EntryNodePort is the fixed node port allocated to the load entrypoint
	// Service when Options.NodePort is set.
	EntryNodePort = 30080

	// The generated Postgres Deployment and the DSNs rendered into node
	// configs share these credentials. Demo-grade by design.
	postgresUser     = "zealot"
	postgresPassword = "zealot"
)

// Options controls manifest rendering.
type Options struct {
	// Image is the zealot container image for every service Deployment
	// (default "zealot:latest").
	Image string
	// NodePort exposes the load entrypoint Service on EntryNodePort so k6
	// outside the cluster can reach it.
	NodePort bool
	// PrometheusOperator emits one ServiceMonitor per zealot service.
	PrometheusOperator bool
}

// File is one rendered manifest file (multi-document YAML).
type File struct {
	// Name is the file name relative to the output directory.
	Name    string
	Content string
}

// Render produces the manifest files for a validated topology, in
// deterministic order: namespace, datastores (sorted), services (sorted).
func Render(top *topology.Topology, opts Options) ([]File, error) {
	if opts.Image == "" {
		opts.Image = "zealot:latest"
	}
	if opts.NodePort && (top.Load == nil || top.Load.Entrypoint == "") {
		return nil, fmt.Errorf("--nodeport requires load.entrypoint in the topology")
	}
	g := &generator{top: top, opts: opts}
	header := fmt.Sprintf("# Generated by zealot generate from topology %q — do not edit.\n", top.Name)

	files := []File{}
	ns, err := renderDocs(header, g.namespace())
	if err != nil {
		return nil, err
	}
	files = append(files, File{Name: "00-namespace.yaml", Content: ns})
	for _, name := range sortedKeys(top.Datastores) {
		content, err := g.datastore(name, header)
		if err != nil {
			return nil, err
		}
		files = append(files, File{Name: name + ".yaml", Content: content})
	}
	for _, name := range sortedKeys(top.Services) {
		content, err := g.service(name, header)
		if err != nil {
			return nil, err
		}
		files = append(files, File{Name: name + ".yaml", Content: content})
	}
	return files, nil
}

// Write renders manifests and writes them into dir (created if needed),
// returning the written paths.
func Write(top *topology.Topology, dir string, opts Options) ([]string, error) {
	files, err := Render(top, opts)
	if err != nil {
		return nil, err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, fmt.Errorf("create output dir: %w", err)
	}
	var paths []string
	for _, f := range files {
		p := filepath.Join(dir, f.Name)
		if err := os.WriteFile(p, []byte(f.Content), 0o644); err != nil {
			return nil, fmt.Errorf("write %s: %w", p, err)
		}
		paths = append(paths, p)
	}
	return paths, nil
}

// generator holds the render state shared by the per-resource builders.
type generator struct {
	top  *topology.Topology
	opts Options
}

// renderDocs marshals docs as a multi-document YAML file with header.
func renderDocs(header string, docs ...any) (string, error) {
	var b strings.Builder
	b.WriteString(header)
	for _, doc := range docs {
		out, err := yaml.Marshal(doc)
		if err != nil {
			return "", fmt.Errorf("render manifest: %w", err)
		}
		b.WriteString("---\n")
		b.Write(out)
	}
	return b.String(), nil
}

func (g *generator) namespace() namespaceDoc {
	return namespaceDoc{
		APIVersion: "v1",
		Kind:       "Namespace",
		Metadata:   metadata{Name: g.top.Namespace},
	}
}

// service renders the ConfigMap (node config), Deployment and Service for
// one zealot service, plus a ServiceMonitor when requested.
func (g *generator) service(name, header string) (string, error) {
	svc := g.top.Services[name]
	nodeYAML, err := yaml.Marshal(g.nodeConfig(name, svc))
	if err != nil {
		return "", fmt.Errorf("render node config for %q: %w", name, err)
	}
	labels := map[string]string{"app": name}
	cm := configMapDoc{
		APIVersion: "v1",
		Kind:       "ConfigMap",
		Metadata:   metadata{Name: name + "-config", Namespace: g.top.Namespace, Labels: labels},
		Data:       map[string]string{"node.yaml": string(nodeYAML)},
	}
	docs := []any{cm, g.zealotDeployment(name, svc), g.zealotService(name)}
	if g.opts.PrometheusOperator {
		docs = append(docs, g.serviceMonitor(name))
	}
	return renderDocs(header, docs...)
}

// nodeConfig builds the per-instance node config baked into the ConfigMap.
// Only datastores actually referenced by the service's query steps are
// included; they point at the datastore's cluster Service.
func (g *generator) nodeConfig(name string, svc topology.Service) config.NodeConfig {
	cfg := config.NodeConfig{
		Service:   name,
		Listen:    fmt.Sprintf(":%d", zealotPort),
		Endpoints: svc.Endpoints,
	}
	refs := map[string]bool{}
	for _, ep := range svc.Endpoints {
		for _, step := range ep.Pipeline {
			if step.Query != nil {
				refs[step.Query.Datastore] = true
			}
		}
	}
	if len(refs) == 0 {
		return cfg
	}
	cfg.Datastores = make(map[string]config.Datastore, len(refs))
	for ref := range refs {
		ds := g.top.Datastores[ref]
		switch ds.Type {
		case "postgres":
			cfg.Datastores[ref] = config.Datastore{
				Driver: "postgres",
				DSN: fmt.Sprintf("postgres://%s:%s@%s:5432/%s?sslmode=disable",
					postgresUser, postgresPassword, ref, ds.Database),
			}
		case "redis":
			cfg.Datastores[ref] = config.Datastore{
				Driver: "redis",
				Addr:   ref + ":6379",
			}
		}
	}
	return cfg
}

// datastore renders a datastore's manifests: Postgres gets a PVC, an
// optional initdb ConfigMap (seedSQL), a Deployment and a Service; Redis
// gets a Deployment and a Service.
func (g *generator) datastore(name, header string) (string, error) {
	ds := g.top.Datastores[name]
	labels := map[string]string{"app": name}
	meta := metadata{Name: name, Namespace: g.top.Namespace, Labels: labels}
	var docs []any
	switch ds.Type {
	case "postgres":
		docs = append(docs, persistentVolumeClaimDoc{
			APIVersion: "v1",
			Kind:       "PersistentVolumeClaim",
			Metadata:   metadata{Name: name + "-data", Namespace: g.top.Namespace, Labels: labels},
			Spec: pvcSpec{
				AccessModes: []string{"ReadWriteOnce"},
				Resources:   pvcResources{Requests: map[string]string{"storage": "1Gi"}},
			},
		})
		if ds.SeedSQL != "" {
			docs = append(docs, configMapDoc{
				APIVersion: "v1",
				Kind:       "ConfigMap",
				Metadata:   metadata{Name: name + "-initdb", Namespace: g.top.Namespace, Labels: labels},
				Data:       map[string]string{"init.sql": ds.SeedSQL},
			})
		}
		docs = append(docs, g.postgresDeployment(name, ds, meta),
			g.datastoreService(meta, "postgres", 5432))
	case "redis":
		docs = append(docs, g.redisDeployment(ds, meta),
			g.datastoreService(meta, "redis", 6379))
	default:
		return "", fmt.Errorf("datastore %q: unsupported type %q (validate the topology first)", name, ds.Type)
	}
	return renderDocs(header, docs...)
}

func (g *generator) zealotDeployment(name string, svc topology.Service) deploymentDoc {
	meta := metadata{Name: name, Namespace: g.top.Namespace, Labels: map[string]string{"app": name}}
	c := container{
		Name:            "zealot",
		Image:           g.opts.Image,
		ImagePullPolicy: "IfNotPresent",
		Args:            []string{"serve", "--config", "/etc/zealot/node.yaml"},
		Ports:           []containerPort{{Name: "http", ContainerPort: zealotPort}},
		Resources:       resourcesFor(svc.Resources),
		ReadinessProbe:  &probe{HTTPGet: &httpGet{Path: "/healthz", Port: "http"}},
		LivenessProbe:   &probe{HTTPGet: &httpGet{Path: "/healthz", Port: "http"}},
		VolumeMounts:    []volumeMount{{Name: "config", MountPath: "/etc/zealot", ReadOnly: true}},
	}
	return g.deployment(meta, svc.Replicas, c,
		[]volume{{Name: "config", ConfigMap: &configMapVol{Name: name + "-config"}}})
}

func (g *generator) zealotService(name string) serviceDoc {
	spec := serviceSpec{
		Selector: map[string]string{"app": name},
		Ports: []servicePort{{
			Name:       "http",
			Port:       80,
			TargetPort: "http",
		}},
	}
	if g.opts.NodePort && g.top.Load.Entrypoint == name {
		spec.Type = "NodePort"
		spec.Ports[0].NodePort = EntryNodePort
	}
	return serviceDoc{
		APIVersion: "v1",
		Kind:       "Service",
		Metadata:   metadata{Name: name, Namespace: g.top.Namespace, Labels: map[string]string{"app": name}},
		Spec:       spec,
	}
}

func (g *generator) serviceMonitor(name string) serviceMonitorDoc {
	labels := map[string]string{"app": name}
	return serviceMonitorDoc{
		APIVersion: "monitoring.coreos.com/v1",
		Kind:       "ServiceMonitor",
		Metadata:   metadata{Name: name, Namespace: g.top.Namespace, Labels: labels},
		Spec: serviceMonitorSpec{
			Selector:  selector{MatchLabels: labels},
			Endpoints: []monitorEndpoint{{Port: "http"}},
		},
	}
}

func (g *generator) postgresDeployment(name string, ds topology.Datastore, meta metadata) deploymentDoc {
	c := container{
		Name:  "postgres",
		Image: ds.Image,
		Ports: []containerPort{{Name: "postgres", ContainerPort: 5432}},
		Env: []envVar{
			{Name: "POSTGRES_USER", Value: postgresUser},
			{Name: "POSTGRES_PASSWORD", Value: postgresPassword},
			{Name: "POSTGRES_DB", Value: ds.Database},
			// Subdirectory avoids initdb failures on volumes with a
			// lost+found directory.
			{Name: "PGDATA", Value: "/var/lib/postgresql/data/pgdata"},
		},
		ReadinessProbe: &probe{Exec: &execProbe{
			Command: []string{"pg_isready", "-U", postgresUser, "-d", ds.Database},
		}},
		VolumeMounts: []volumeMount{{Name: "data", MountPath: "/var/lib/postgresql/data"}},
	}
	volumes := []volume{{Name: "data", PVC: &pvcVol{ClaimName: name + "-data"}}}
	if ds.SeedSQL != "" {
		c.VolumeMounts = append(c.VolumeMounts,
			volumeMount{Name: "initdb", MountPath: "/docker-entrypoint-initdb.d", ReadOnly: true})
		volumes = append(volumes, volume{Name: "initdb", ConfigMap: &configMapVol{Name: name + "-initdb"}})
	}
	return g.deployment(meta, 1, c, volumes)
}

func (g *generator) redisDeployment(ds topology.Datastore, meta metadata) deploymentDoc {
	c := container{
		Name:           "redis",
		Image:          ds.Image,
		Ports:          []containerPort{{Name: "redis", ContainerPort: 6379}},
		ReadinessProbe: &probe{Exec: &execProbe{Command: []string{"redis-cli", "ping"}}},
	}
	return g.deployment(meta, 1, c, nil)
}

func (g *generator) datastoreService(meta metadata, portName string, port int) serviceDoc {
	return serviceDoc{
		APIVersion: "v1",
		Kind:       "Service",
		Metadata:   meta,
		Spec: serviceSpec{
			Selector: map[string]string{"app": meta.Name},
			Ports: []servicePort{{
				Name:       portName,
				Port:       port,
				TargetPort: portName,
			}},
		},
	}
}

// deployment builds one Deployment selecting on the app label from meta.
func (g *generator) deployment(meta metadata, replicas int, c container, volumes []volume) deploymentDoc {
	labels := map[string]string{"app": meta.Name}
	return deploymentDoc{
		APIVersion: "apps/v1",
		Kind:       "Deployment",
		Metadata:   meta,
		Spec: deploymentSpec{
			Replicas: replicas,
			Selector: selector{MatchLabels: labels},
			Template: podTemplate{
				Metadata: metadata{Labels: labels},
				Spec:     podSpec{Containers: []container{c}, Volumes: volumes},
			},
		},
	}
}

// resourcesFor maps topology resources to Kubernetes requests=limits (a
// single value throttles deterministically in CPU demos). Nil when unset.
func resourcesFor(r topology.Resources) *resourceRequirements {
	q := map[string]string{}
	if r.CPU != "" {
		q["cpu"] = r.CPU
	}
	if r.Memory != "" {
		q["memory"] = r.Memory
	}
	if len(q) == 0 {
		return nil
	}
	return &resourceRequirements{Requests: q, Limits: q}
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
